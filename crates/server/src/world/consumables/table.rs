//! The `Consumables` enum of content/data/consumables/Consumables.java: every
//! constant in declaration order with its consumable's class, item ids,
//! animation, messages, effect and `isIgnoreMainClock`.
use super::effects::{Diary, Effect, TimerArg};
use super::{Consumable, Kind};

/// One `Consumables` constant.
pub struct Row {
    pub name: &'static str,
    pub consumable: Consumable,
    pub ignore_main_clock: bool,
}

fn row(
    name: &'static str,
    kind: Kind,
    ids: &[i32],
    animation: Option<i32>,
    messages: &[&str],
    effect: Option<Effect>,
    ignore_main_clock: bool,
) -> Row {
    Row {
        name,
        consumable: Consumable {
            kind,
            ids: ids.to_vec(),
            effect,
            animation,
            messages: messages.iter().map(|m| (*m).to_string()).collect(),
        },
        ignore_main_clock,
    }
}

fn heal(amount: i32) -> Effect {
    Effect::Healing(amount)
}

fn skill(slot: i32, base: f64, bonus: f64) -> Effect {
    Effect::Skill { slot, base, bonus }
}

fn multi(effects: Vec<Effect>) -> Effect {
    Effect::Multi(effects)
}

