"""Transcribe pinned CollisionMap size>1 wall/decor branches into Rust."""
import argparse,hashlib,importlib.util,pathlib,re,subprocess
ROOT=pathlib.Path(__file__).resolve().parents[1]
OUT=ROOT/'crates/client/src/route_reach.rs'
spec=importlib.util.spec_from_file_location('reach_visual',ROOT/'oracle/visual/generate.py')
v=importlib.util.module_from_spec(spec);spec.loader.exec_module(v)

def block(text,start):
    opening=text.index('{',start);end=opening+1;depth=1
    while depth:
        depth+=(text[end]=='{')-(text[end]=='}');end+=1
    return text[opening+1:end-1],end

def generate():
    raw=(ROOT/'reference/client/client/src/main/java/rt4/CollisionMap.java').read_bytes().replace(b'\r\n',b'\n')
    source=v.clean(raw.decode());out='//! Generated by tools/port_client_reach.py; original branch order is retained.\n'
    out+='//! CollisionMap.java SHA256: '+hashlib.sha256(raw).hexdigest()+'\n'
    out+='use rs09_game_core::collision::CollisionMap;\n'
    out+='fn flag(map:&CollisionMap,x:i32,y:i32)->i32{map.get(x,y).unwrap_or(i32::MAX)}\n'
    for java,rust in [('isAtWall','wall'),('isAtWallDecor','decoration')]:
        method=v.method(source,'public final boolean '+java+'(')
        occurrences=list(re.finditer(r'if \(size == 1\)',method));assert len(occurrences)==2
        _,end=block(method,occurrences[1].start());assert method[end:].lstrip().startswith('else {')
        body,_=block(method,end)
        body=re.sub(r'\bint (\w+) =',r'let \1 =',body)
        body=re.sub(r'this\.flags\[([^\]]+)\]\[([^\]]+)\]',r'flag(map,\1,\2)',body)
        body=re.sub(r'\bif \((.*)\) \{',r'if \1 {',body)
        names={'destType':'kind','destAngle':'angle','endX':'end_x','endY':'end_y','startX':'start_x','startY':'start_y'}
        for old,new in names.items():body=re.sub(r'\b'+old+r'\b',new,body)
        body=body.replace('angle = angle + 2 & 0x3;', 'angle = (angle + 2) & 0x3;')
        mutate='mut 'if re.search(r'\bangle\s*=(?!=)',body)else''
        out+='#[allow(clippy::collapsible_if)]\n'
        out+=f'pub(crate) fn {rust}(map:&CollisionMap,actor:[i32;2],target:[i32;2],size:i32,kind:i32,{mutate}angle:i32)->bool{{\n'
        # The original early condition omits the actor Y coordinate. Its final
        # term is intentional, including original signed-overflow semantics.
        out+='if actor[0]<=target[0]&&actor[0].wrapping_add(size).wrapping_sub(1)>=target[0]&&target[1]<=target[1].wrapping_add(size).wrapping_sub(1){return true;}\n'
        out+='let [end_x,end_y]=actor;let [start_x,start_y]=target;\n'+body+'\nfalse\n}\n'
    out+=RECTANGLE
    result=subprocess.run(['rustfmt','--edition','2024','--emit','stdout'],input=out,text=True,capture_output=True,check=True)
    return result.stdout

RECTANGLE='''
pub(crate) fn rectangle(map:&CollisionMap,p:[i32;2],size:i32,t:[i32;2],dims:[i32;2],blocked:i32)->bool{
 let [x,y]=p;let [tx,ty]=t;let [w,h]=dims;
 let right=x+size;let top=y+size;let tr=tx+w;let tt=ty+h;
 if x<tr&&right>tx&&y<tt&&top>ty{return true;}
 // isOutsideRect tests whether an actor span endpoint lies in the target.
 // Strictly covering the target span does not enter that contact branch.
 let horizontal=(tx..tr).contains(&x)||(tx<right&&right<=tr);
 let vertical=(ty..tt).contains(&y)||(ty<top&&top<=tt);
 if horizontal {
  if top==ty&&blocked&4==0{return (x.max(tx)..right.min(tr)).any(|i|flag(map,i,top-1)&2==0);}
  if y==tt&&blocked&1==0{return (x.max(tx)..right.min(tr)).any(|i|flag(map,i,y)&32==0);}
 } else if vertical {
  if right==tx&&blocked&8==0{return (y.max(ty)..top.min(tt)).any(|i|flag(map,right-1,i)&8==0);}
  if x==tr&&blocked&2==0{return (y.max(ty)..top.min(tt)).any(|i|flag(map,x,i)&128==0);}
 }
 false
}
'''

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args();content=generate()
    if args.check:
        if OUT.read_text()!=content:raise SystemExit('Client sized-reach transcription differs')
    else:OUT.write_text(content)
    print('Pinned client sized wall/decor reach branches match transcription',flush=True)
