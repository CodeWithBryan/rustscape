/// The definer of a class, if it defines commands.
pub fn definer(class: &str) -> Option<&'static Definer> {
    DEFINERS.iter().find(|d| d.class == class)
}

/// Registers one class's commands, in order.
pub fn register_class(registry: &mut Registry, definer: &Definer) {
    for define in definer.defines {
        registry.register(Command {
            name: define.name.to_owned(),
            privilege: define.privilege,
            usage: define.usage.to_owned(),
            description: define.description.to_owned(),
            body: match define.native {
                Some(native) => Body::Native(native),
                None => Body::Content(ContentBody {
                    class: definer.class,
                    lambda: define.lambda,
                }),
            },
            origin: ContentBody {
                class: definer.class,
                lambda: define.lambda,
            },
        });
    }
}

/// The registry the class scan leaves: the content-interface list (a
/// `WorldEvent` only when `active` says it is), then the `@Initializable`
/// list. `active` is the boot's `WorldEvent.checkActive` answer, a host
/// input (it reads the start-up clock).
pub fn register_all(active: &dyn Fn(&str) -> bool) -> Registry {
    let mut registry = Registry::new();
    let manifest = scan::Manifest::load();
    for class in &manifest.content_interfaces {
        if let Some(definer) = definer(class)
            && definer.kind == Kind::Content
            && (!WORLD_EVENTS.contains(class) || active(class))
        {
            register_class(&mut registry, definer);
        }
    }
    for class in &manifest.initializable {
        if let Some(definer) = definer(class)
            && definer.kind == Kind::Plugin
        {
            register_class(&mut registry, definer);
        }
        if let Some((plugin, sets)) = LEGACY.iter().find(|(name, _)| name == class) {
            for set in *sets {
                registry.link(*set, plugin);
            }
        }
    }
    registry
}

/// The definers that are `WorldEvent`s: `loadContentInterfacesFrom` skips
/// one whose `checkActive(STARTUP_MOMENT)` is false before it defines
/// anything.
pub const WORLD_EVENTS: &[&str] = &["core.game.worldevents.holiday.easter.EasterEvent"];

/// The world events the pinned boot found active among [`WORLD_EVENTS`]:
/// none (EasterEvent registers no listener in the world-trace boot).
pub fn pinned_boot_active(_class: &str) -> bool {
    false
}

/// The subset of the registry the behaviour corpus compiles: these sets'
/// classes registered in scan order.
pub fn register_only(classes: &[&str]) -> Registry {
    let mut registry = Registry::new();
    let manifest = scan::Manifest::load();
    for class in manifest
        .content_interfaces
        .iter()
        .chain(&manifest.initializable)
    {
        if classes.contains(class)
            && let Some(definer) = definer(class)
        {
            register_class(&mut registry, definer);
        }
    }
    registry
}
