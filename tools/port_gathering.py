"""Author the native gathering row tables from the pinned enum declarations.

Reads the unmodified WoodcuttingNode, MiningNode, SkillingResource,
SkillingTool, Fish, FishingOption and FishingSpot sources and writes their
constructor arguments, in declaration order, to
crates/server/src/world/gathering/tables.rs. The constructor bodies
(the identifier switches) are ported by hand in the gathering module; the JVM
corpus under fixtures/gathering compares every resulting field with the real
enum objects. --check verifies the committed table without writing.
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
MAIN = ROOT / "reference/server/Server/src/main"
OUTPUT = ROOT / "crates/server/src/world/gathering/tables.rs"
ROW = re.compile(r"^\s*([A-Z][A-Z_0-9]*)\((.*)\)\s*[,;]?\s*(?://.*)?$")


def read(path):
    return (MAIN / path).read_bytes().replace(b"\r", b"").decode("utf-8")


def rows(text, stop):
    """Enum constants precede the first member declaration (`stop`)."""
    body = text[text.index("{") + 1 : text.index(stop)]
    out = []
    for line in body.split("\n"):
        match = ROW.match(line)
        if match:
            out.append((match.group(1), [part.strip() for part in match.group(2).split(",")]))
    return out


def skills():
    text = read("core/game/node/entity/skill/Skills.java")
    line = re.search(r"public static final int (ATTACK = 0,[^;]*);", text).group(1)
    return {name: int(value) for name, value in re.findall(r"([A-Z]+) = (\d+)", line)}


SKILLS = skills()


def integer(text):
    text = text.strip()
    if text.startswith("(byte)"):
        value = integer(text[6:])
        assert -128 <= value <= 127
        return value
    if "|" in text:
        left, right = text.split("|")
        return to_i32(integer(left) | integer(right))
    if "<<" in text:
        left, right = text.split("<<")
        return to_i32(integer(left) << integer(right))
    if text == "Integer.MAX_VALUE":
        return 2147483647
    if text.startswith("Skills."):
        return SKILLS[text[7:]]
    if text.startswith("Items."):
        # ConstLib names end in the item id; the JVM corpus checks the value.
        return int(text.rsplit("_", 1)[1])
    return int(text)


def to_i32(value):
    value &= 0xFFFFFFFF
    return value - (1 << 32) if value & 0x80000000 else value


def double(text):
    text = text.strip().rstrip("Dd")
    float(text)
    return text if "." in text else text + ".0"


def boolean(text):
    assert text in ("true", "false")
    return text


def string(text):
    assert re.fullmatch(r'"[a-z ]*"', text), text
    return text


def animation(text):
    match = re.fullmatch(r"new Animation\((\d+)\)", text)
    assert match, text
    return int(match.group(1))


def generate():
    out = [
        "// @generated by tools/port_gathering.py from the pinned enum declarations.",
        "// Constructor arguments in declaration order; do not edit by hand.",
        "#![allow(clippy::unreadable_literal, clippy::type_complexity)]",
        "",
        "/// WoodcuttingNode(full, empty, identifier[, farming]); `None` is the three-argument constructor.",
        "#[rustfmt::skip]",
        "pub const WOODCUTTING_ROWS: &[(&str, i32, i32, i8, Option<bool>)] = &[",
    ]
    for name, a in rows(read("content/global/skill/gather/woodcutting/WoodcuttingNode.java"), "int full,empty"):
        assert len(a) in (3, 4)
        farming = "None" if len(a) == 3 else f"Some({boolean(a[3])})"
        out.append(f'    ("{name}", {integer(a[0])}, {integer(a[1])}, {integer(a[2])}, {farming}),')
    out += ["];", "", "/// MiningNode(full, empty, identifier).", "#[rustfmt::skip]", "pub const MINING_ROWS: &[(&str, i32, i32, i8)] = &["]
    for name, a in rows(read("content/global/skill/gather/mining/MiningNode.java"), "public static List<WeightedChanceItem>"):
        assert len(a) == 3
        out.append(f'    ("{name}", {integer(a[0])}, {integer(a[1])}, {integer(a[2])}),')
    out += [
        "];",
        "",
        "/// SkillingResource(id, level, rate, respawnRate, experience, reward, rewardAmount, name, emptyId, skillId, farming).",
        "/// Every pinned row passes a null Animation; `farming` is false for the eleven-argument constructor.",
        "#[rustfmt::skip]",
        "pub const RESOURCE_ROWS: &[(&str, i32, i32, f64, i32, f64, i32, i32, &str, i32, i32, bool)] = &[",
    ]
    for name, a in rows(read("content/global/skill/gather/SkillingResource.java"), "private static final Map"):
        assert len(a) in (11, 12) and a[8] == "null", (name, a)
        farming = boolean(a[11]) if len(a) == 12 else "false"
        out.append(
            f'    ("{name}", {integer(a[0])}, {integer(a[1])}, {double(a[2])}, {integer(a[3])}, {double(a[4])}, '
            f"{integer(a[5])}, {integer(a[6])}, {string(a[7])}, {integer(a[9])}, {integer(a[10])}, {farming}),"
        )
    out += ["];", "", "/// SkillingTool(id, level, ratio, new Animation(id)).", "#[rustfmt::skip]", "pub const TOOL_ROWS: &[(&str, i32, i32, f64, i32)] = &["]
    for name, a in rows(read("content/data/skill/SkillingTool.java"), "private final int id"):
        assert len(a) == 4
        out.append(f'    ("{name}", {integer(a[0])}, {integer(a[1])}, {double(a[2])}, {animation(a[3])}),')
    out += ["];", ""]
    out += fishing()
    return "\n".join(out)


def constant(text):
    """`Items.NAME_123` / `NPCs.NAME_123`: ConstLib names end in the id; the JVM corpus checks the value."""
    match = re.fullmatch(r"\(?(?:Items|NPCs)\.[A-Z_0-9]*_(\d+)\)?", text.strip())
    assert match, text
    return int(match.group(1))


def fishing():
    """Fish, FishingOption and FishingSpot (Kotlin enums); cross references are written as ordinals."""
    fish_text = read("content/global/skill/fishing/Fish.kt")
    fish = rows(fish_text, "companion object")
    out = ["/// Fish(id, level, experience, lowChance, highChance).", "#[rustfmt::skip]", "pub const FISH_ROWS: &[(&str, i32, i32, f64, f64, f64)] = &["]
    for name, a in fish:
        assert len(a) == 5, (name, a)
        out.append(f'    ("{name}", {constant(a[0])}, {integer(a[1])}, {double(a[2])}, {double(a[3])}, {double(a[4])}),')
    fish_index = {name: index for index, (name, _) in enumerate(fish)}
    big = re.findall(r"bigFishMap\[Fish\.([A-Z_]+)\]\s*=\s*(Items\.[A-Z_0-9]+)", fish_text)
    assert big
    out += ["];", "", "/// `Fish.bigFishMap` puts, in source order: (fish ordinal, item).", "#[rustfmt::skip]", "pub const BIG_FISH_ROWS: &[(usize, i32)] = &["]
    out += [f"    ({fish_index[name]}, {constant(item)})," for name, item in big]
    out += ["];", ""]
    for field, kind in [("barehandFishingReq", "i32"), ("barehandStrengthReq", "i32"), ("barehandStrengthXp", "f64")]:
        body = re.search(field + r" = mapOf\(([^)]*)\)", fish_text).group(1)
        pairs = re.findall(r"([A-Z_]+) to ([0-9.]+)", body)
        assert pairs and len(pairs) == body.count(" to ")
        const = re.sub(r"([A-Z])", r"_\1", field).upper()
        out += [f"/// `Fish.{field}`, in source order: (fish ordinal, value).", "#[rustfmt::skip]", f"pub const {const}: &[(usize, {kind})] = &["]
        out += [f"    ({fish_index[name]}, {integer(value) if kind == 'i32' else double(value)})," for name, value in pairs]
        out += ["];", ""]
    option_text = read("content/global/skill/fishing/FishingOption.kt")
    body = option_text[option_text.index("{") + 1 : option_text.index("companion object")]
    pattern = re.compile(
        r'^\s*([A-Z_]+)\((Items\.[A-Z_0-9]+), (\d+), Animation\((\d+)\), (null|intArrayOf\(([^"]*)\)), "([a-z]+)", ((?:Fish\.[A-Z_]+(?:, )?)+)\)[,;]\s*$'
    )
    options = []
    out += [
        "/// FishingOption(tool, level, Animation(id), bait, option, fish...); fish are `Fish` ordinals.",
        "#[rustfmt::skip]",
        "pub const FISHING_OPTION_ROWS: &[(&str, i32, i32, i32, Option<&[i32]>, &str, &[usize])] = &[",
    ]
    for line in body.split("\n"):
        if not line.strip():
            continue
        match = pattern.match(line)
        assert match, line
        name, tool, level, anim, bait, baits, option, caught = match.groups()
        bait = "None" if bait == "null" else "Some(&[" + ", ".join(str(constant(b)) for b in baits.split(",")) + "])"
        caught = ", ".join(str(fish_index[f.strip()[5:]]) for f in caught.split(","))
        options.append(name)
        out.append(f'    ("{name}", {constant(tool)}, {int(level)}, {int(anim)}, {bait}, "{option}", &[{caught}]),')
    assert len(options) == len(re.findall(r"^\s*[A-Z_]+\(Items\.", body, re.M))
    option_index = {name: index for index, name in enumerate(options)}
    spot_text = read("content/global/skill/fishing/FishingSpot.kt")
    body = spot_text[spot_text.index("{") + 1 : spot_text.index("companion object")]
    spots = re.findall(r"([A-Z_]+)\(\s*intArrayOf\(([^)]*)\),([^)]*)\)", body)
    assert len(spots) == body.count("intArrayOf(")
    out += ["];", "", "/// FishingSpot(ids, options...); options are `FishingOption` ordinals.", "#[rustfmt::skip]", "pub const FISHING_SPOT_ROWS: &[(&str, &[i32], &[usize])] = &["]
    for name, ids, opts in spots:
        ids = ", ".join(str(constant(i)) for i in ids.split(",") if i.strip())
        opts = ", ".join(str(option_index[o.strip()[14:]]) for o in opts.split(",") if o.strip())
        out.append(f'    ("{name}", &[{ids}], &[{opts}]),')
    out += ["];", ""]
    return out


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if OUTPUT.read_bytes().replace(b"\r", b"").decode("utf-8") != text:
            sys.exit("gathering tables differ from the pinned enum declarations")
        print("gathering tables match the pinned enum declarations")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUTPUT.relative_to(ROOT).as_posix()}")
