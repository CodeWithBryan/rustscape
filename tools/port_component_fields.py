"""Generate the RT4 Component data fields/defaults; never execute Java at runtime."""
import argparse, hashlib, pathlib, re, subprocess
ROOT=pathlib.Path(__file__).resolve().parents[1]
SOURCE=ROOT/'reference/client/client/src/main/java/rt4/Component.java'
OUTPUT=ROOT/'crates/client/src/ui/component_fields.rs'
def fields():
    raw=SOURCE.read_text(encoding='utf-8').split('public static void clean()')[0]
    return [(t,n,v) for static,t,n,v in re.findall(r'(?:public|private)\s+(static\s+)?(int\[\]\[\]|int\[\]|byte\[\]|Object\[\]|JagString\[\]|JagString|ServerActiveProperties|boolean|int|byte|short)\s+(\w+)(?:\s*=\s*([^;]+))?;',raw) if not static]
def snake(s):return re.sub(r'(?<!^)(?=[A-Z])','_',s).lower().replace('type','kind') if s=='type' else re.sub(r'(?<!^)(?=[A-Z])','_',s).lower()
def generate():
    out=['// Generated by tools/port_component_fields.py from pinned Component.java.',f'// SHA256 {hashlib.sha256(SOURCE.read_bytes().replace(bytes([13,10]),bytes([10]))).hexdigest()}','use super::{HookArg, Properties};','use serde::Serialize;','#[derive(Clone, Debug, Serialize)]','pub struct Component {']
    defaults=[]
    for typ,name,value in fields():
        rust={'int':'i32','byte':'i32','short':'i32','boolean':'bool','JagString':'String','ServerActiveProperties':'Properties','Object[]':'Option<Vec<HookArg>>','JagString[]':'Option<Vec<Option<String>>>','int[]':'Option<Vec<i32>>','byte[]':'Option<Vec<i32>>','int[][]':'Option<Vec<Vec<i32>>>'}[typ]
        if typ.endswith('[]'):value='None'
        elif typ=='JagString':value='"Ok".into()' if value=='LocalizedText.OK' else 'String::new()'
        elif typ=='ServerActiveProperties':value='Properties::default()'
        elif not value:value='false' if typ=='boolean' else '0'
        out.extend([f'    #[serde(rename = "{name}")]',f'    pub {snake(name)}: {rust},'])
        defaults.append(f'            {snake(name)}: {value},')
    out.extend(['}','impl Default for Component {','    fn default() -> Self {','        Self {',*defaults,'        }','    }','}'])
    return '\n'.join(out)+'\n'
if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    OUTPUT.parent.mkdir(exist_ok=True)
    temp=ROOT/'runs/component_fields.rs';temp.parent.mkdir(exist_ok=True);temp.write_text(generate(),encoding='utf-8')
    subprocess.run(['rustfmt','--edition','2024',str(temp)],check=True)
    result=temp.read_bytes()
    if args.check:
        if OUTPUT.read_bytes()!=result:raise SystemExit('Component field port is stale')
    else:OUTPUT.write_bytes(result)
