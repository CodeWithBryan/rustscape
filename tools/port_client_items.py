def fields():
    raw=SOURCE.read_text(encoding='utf-8').split('public final ObjType getCountVariant')[0]
    return [(t,n,value)for static,t,n,value in re.findall(r'(?:public|private)\s+(static\s+)?(short\[\]|int\[\]|byte\[\]|JagString\[\]|JagString|HashTable|boolean|int)\s+(\w+)(?:\s*=\s*([^;]+))?;',raw)if not static]
def generate():
    out=['// Generated by tools/port_client_items.py from pinned ObjType.java.',f'// SHA256 {hashlib.sha256(SOURCE.read_bytes().replace(bytes([13,10]),bytes([10]))).hexdigest()}','use super::HookArg;','use serde::Serialize;','use std::collections::BTreeMap;','#[derive(Clone, Debug, Serialize)]','#[allow(non_snake_case)]','pub struct ItemType {'];defaults=[];types={}
