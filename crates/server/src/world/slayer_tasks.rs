/// `Tasks.forId(id)`: the task's constant name and `levelReq`, or `None`.
pub fn for_id(id: i32) -> Option<(&'static str, i32)> {
    TASKS
        .binary_search_by_key(&id, |&(npc, _, _)| npc)
        .ok()
        .map(|at| (TASKS[at].1, TASKS[at].2))
}

/// `Tasks.forId(id).levelReq`, or `None` when the id has no task.
pub fn level_req(id: i32) -> Option<i32> {
    for_id(id).map(|(_, level)| level)
}
