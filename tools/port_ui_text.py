"""Author the pinned byte sort table used by JagString.compare."""
import hashlib,pathlib,re,subprocess,sys,tempfile
root=pathlib.Path(__file__).resolve().parents[1]
source=(root/'reference/client/client/src/main/java/rt4/JagString.java').read_bytes().replace(b'\r\n',b'\n')
values=re.search(rb'CHAR_SORT_ORDER = new int\[\]\{([^}]+)\}',source)[1].decode()
rust='// Generated by tools/port_ui_text.py; source SHA256 '+hashlib.sha256(source).hexdigest()+'\npub const ORDER: [u8;256] = ['+values+'];\n'
with tempfile.TemporaryDirectory()as tmp:
    p=pathlib.Path(tmp)/'order.rs';p.write_text(rust);subprocess.run(['rustfmt',str(p)],check=True);data=p.read_bytes()
out=root/'crates/client/src/ui/text_order.rs'
if '--check'in sys.argv:
    if out.read_bytes()!=data:raise SystemExit('Pinned client sort table differs')
else:out.write_bytes(data)
