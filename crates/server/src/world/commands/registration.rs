//! The command registrations of the class scan, in the original's order.
//!
//! The original fills `CommandMapping` while `ClassScanner` loads the scanned
//! classes: `loadPureInterfaces` calls `defineCommands()` on every content
//! class that is a `Commands` (a `WorldEvent` only when it is active), then
//! `loadSideEffectfulPlugins` calls `newInstance` on every `@Initializable`
//! plugin, which for a `sets.CommandSet` runs its `defineCommands()` and for
//! a legacy `CommandPlugin` links it to the `CommandSet` constants it names.
//! [`register_all`] walks the scan manifest of `crate::startup::scan` and
//! registers each class's [`Define`]s in their source order (the order of
//! their handler lambdas, `Class$defineCommands$N`). A define with a
//! [`NativeBody`] runs natively; every other one is a [`ContentBody`] the
//! host runs. fixtures/commands/registry.json is what the original's boot
//! leaves; the commands test compares the native result with it.
use super::sets::{SetBody, misc, spawn};
use super::{Body, Command, ContentBody, LegacySet, NativeBody, Privilege, Registry};
use crate::startup::scan;

/// How a class reaches its `defineCommands`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    /// A content class implementing `core.api.Commands` (default privilege
    /// ADMIN): registered from the content-interface list.
    Content,
    /// A `sets.CommandSet` plugin: registered from the `@Initializable` list.
    Plugin,
}

/// One `define(name, privilege, usage, description) { .. }` call.
#[derive(Clone, Copy, Debug)]
pub struct Define {
    pub name: &'static str,
    pub privilege: Privilege,
    pub usage: &'static str,
    pub description: &'static str,
    /// The handler lambda's position: `Class$defineCommands$lambda`.
    pub lambda: u16,
    /// The ported body, if there is one.
    pub native: Option<NativeBody>,
}

/// A class whose `defineCommands` registers commands.
#[derive(Clone, Copy, Debug)]
pub struct Definer {
    pub class: &'static str,
    pub kind: Kind,
    pub defines: &'static [Define],
}

